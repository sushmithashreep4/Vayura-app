export function getAppsForProfile(
  countryCode: string,
  purpose: TravelPurpose,
  limit?: number
): LocalApp[] {
  let filtered = LOCAL_APPS.filter(
    (app) =>
      app.countryCode === countryCode.toUpperCase() &&
      app.supportedPurposes.includes(purpose)
  );

  if (filtered.length === 0) {
    filtered = LOCAL_APPS.filter(
      (app) => app.countryCode === countryCode.toUpperCase()
    );
  }

  // Sort: PayPal integration first, then featured, then by name
  const sorted = filtered.sort((a, b) => {
    if (a.integrationAvailable && !b.integrationAvailable) return -1;
    if (!a.integrationAvailable && b.integrationAvailable) return 1;
    if (a.isFeatured && !b.isFeatured) return -1;
    if (!a.isFeatured && b.isFeatured) return 1;
    return a.name.localeCompare(b.name);
  });

  return limit ? sorted.slice(0, limit) : sorted;
}

export function getAppsByCategory(
  countryCode: string,
  category: AppCategory
): LocalApp[] {
  return LOCAL_APPS.filter(
    (app) =>
      app.countryCode === countryCode.toUpperCase() &&
      app.category === category
  );
}

